function addProduct(p, days) {
  const id = insP.run(p.name, p.days, p.from, p.to, p.pd, p.pt, p.pc, '').lastInsertRowid;
  days.forEach(d => insD.run(id, d[0], d[1], d[2], d[3], d[4]));
  return id;
}

